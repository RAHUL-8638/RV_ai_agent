import React, { useState, useEffect } from 'react';
import {
  Video,
  Play,
  Download,
  Share2,
  Clock,
  Globe2,
  Plus,
  Loader2,
} from 'lucide-react';
import { VideoProject } from '../types';
import { safeFetch } from '../utils/api';

interface VideosPageProps {
  onNavigateToStudio: () => void;
}

export const VideosPage: React.FC<VideosPageProps> = ({ onNavigateToStudio }) => {
  const [publicVideos, setPublicVideos] = useState<VideoProject[]>([]);
  const [loading, setLoading] = useState(true);
  const [playingVideo, setPlayingVideo] = useState<VideoProject | null>(null);
  const [languageFilter, setLanguageFilter] = useState<'all' | 'te' | 'en' | 'hi'>('all');

  useEffect(() => {
    const fetchPublic = async () => {
      try {
        const res = await safeFetch<{ videos: VideoProject[] }>('/api/video/public');
        if (res.ok && res.data?.videos) {
          setPublicVideos(res.data.videos);
        }
      } catch (err) {
        console.warn('Notice fetching public videos:', err);
      } finally {
        setLoading(false);
      }
    };
    fetchPublic();
  }, []);

  const filtered = publicVideos.filter((v) => {
    return languageFilter === 'all' || v.language === languageFilter;
  });

  return (
    <div className="mx-auto max-w-7xl px-4 py-8 sm:px-6">
      <div className="mb-8 flex flex-col md:flex-row md:items-center justify-between gap-4 border-b border-emerald-950/80 pb-6">
        <div>
          <div className="flex items-center gap-2 mb-1">
            <div className="flex h-7 w-7 items-center justify-center rounded border border-emerald-500/50 bg-emerald-950/40 text-emerald-400">
              <Video className="h-4 w-4" />
            </div>
            <h1 className="font-mono text-xl sm:text-2xl font-bold tracking-tight text-white">
              COMMUNITY VIDEO GALLERY
            </h1>
          </div>
          <p className="text-xs text-zinc-400 font-sans">
            AI-synthesized educational animated cybersecurity videos generated by researchers and community educators.
          </p>
        </div>

        <button
          onClick={onNavigateToStudio}
          className="flex items-center gap-2 rounded bg-emerald-500 px-4 py-2 font-mono text-xs font-bold text-black shadow-[0_0_15px_rgba(0,255,102,0.3)] hover:bg-emerald-400 transition-colors whitespace-nowrap self-start md:self-auto"
        >
          <Plus className="h-4 w-4" />
          <span>Synthesize Video with AI Studio</span>
        </button>
      </div>

      {/* Language Filter */}
      <div className="mb-8 flex items-center gap-2">
        <span className="text-xs font-mono text-zinc-500">Language:</span>
        {(['all', 'te', 'en', 'hi'] as const).map((lang) => (
          <button
            key={lang}
            onClick={() => setLanguageFilter(lang)}
            className={`px-3 py-1.5 text-xs font-mono rounded transition-colors ${
              languageFilter === lang
                ? 'border border-emerald-500 bg-emerald-950/60 text-emerald-300 font-bold'
                : 'border border-zinc-800 bg-zinc-950 text-zinc-400 hover:text-zinc-200'
            }`}
          >
            {lang === 'all'
              ? 'All Languages'
              : lang === 'te'
              ? 'తెలుగు (Telugu)'
              : lang === 'en'
              ? 'English'
              : 'हिंदी (Hindi)'}
          </button>
        ))}
      </div>

      {loading ? (
        <div className="flex items-center justify-center py-16 text-xs font-mono text-zinc-500">
          <Loader2 className="h-5 w-5 animate-spin text-emerald-400 mr-2" />
          <span>Loading community video stream...</span>
        </div>
      ) : filtered.length === 0 ? (
        <div className="text-center py-16 border border-zinc-800 rounded-lg bg-zinc-950 text-xs font-mono text-zinc-500 space-y-3">
          <Video className="h-8 w-8 mx-auto text-zinc-700" />
          <p>No public videos published in this category yet.</p>
          <button
            onClick={onNavigateToStudio}
            className="text-emerald-400 hover:underline"
          >
            Be the first to generate and publish an animated cybersecurity video →
          </button>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
          {filtered.map((video) => (
            <div
              key={video.id}
              className="rounded-lg border border-zinc-800 bg-zinc-950/70 overflow-hidden hover:border-emerald-500/50 transition-colors flex flex-col justify-between"
            >
              <div className="relative aspect-video bg-black cursor-pointer group" onClick={() => setPlayingVideo(video)}>
                {video.thumbnailUrl ? (
                  <img
                    src={video.thumbnailUrl}
                    alt={video.title}
                    className="w-full h-full object-cover"
                  />
                ) : (
                  <div className="w-full h-full flex items-center justify-center bg-zinc-900 text-zinc-600 font-mono text-xs">
                    RVCYBER MATRIX VIDEO
                  </div>
                )}
                <div className="absolute inset-0 bg-black/40 flex items-center justify-center opacity-0 group-hover:opacity-100 transition-opacity">
                  <div className="flex h-12 w-12 items-center justify-center rounded-full bg-emerald-500 text-black shadow-[0_0_20px_#00ff66]">
                    <Play className="h-5 w-5 ml-0.5" />
                  </div>
                </div>
                <div className="absolute bottom-2 right-2 rounded bg-black/80 px-1.5 py-0.5 text-[10px] font-mono text-emerald-300">
                  {video.durationSeconds}s
                </div>
              </div>

              <div className="p-4 space-y-3">
                <div>
                  <div className="flex items-center gap-2 text-xs font-mono text-zinc-500 mb-1">
                    <span className="text-emerald-400 font-bold uppercase">{video.language}</span>
                    <span>·</span>
                    <span>{video.audience}</span>
                    <span>·</span>
                    <span>{video.style}</span>
                  </div>
                  <h3 className="text-sm font-bold text-white line-clamp-2">{video.title}</h3>
                </div>

                <div className="flex items-center justify-between pt-2 border-t border-zinc-900 text-xs font-mono">
                  <button
                    onClick={() => setPlayingVideo(video)}
                    className="text-emerald-400 hover:underline flex items-center gap-1"
                  >
                    <Play className="h-3 w-3" />
                    <span>Watch Video</span>
                  </button>

                  <a
                    href={`/api/video/projects/${video.id}/download`}
                    download
                    className="text-zinc-400 hover:text-white flex items-center gap-1"
                  >
                    <Download className="h-3 w-3" />
                    <span>MP4</span>
                  </a>
                </div>
              </div>
            </div>
          ))}
        </div>
      )}

      {/* Video Modal Player */}
      {playingVideo && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/85 p-4 backdrop-blur-sm">
          <div className="w-full max-w-3xl rounded-lg border border-emerald-500/50 bg-zinc-950 p-6 shadow-[0_0_40px_rgba(0,255,102,0.15)] space-y-4">
            <div className="flex items-start justify-between border-b border-zinc-800 pb-3">
              <div>
                <span className="text-xs font-mono text-emerald-400 uppercase">
                  {playingVideo.language} · {playingVideo.durationSeconds} SECONDS
                </span>
                <h3 className="text-lg font-bold text-white mt-0.5">{playingVideo.title}</h3>
              </div>
              <button
                onClick={() => setPlayingVideo(null)}
                className="text-zinc-400 hover:text-white font-mono text-xs"
              >
                ✕ Close
              </button>
            </div>

            <div className="relative aspect-video rounded-lg overflow-hidden bg-black border border-zinc-800">
              <video
                src={playingVideo.videoUrl}
                controls
                autoPlay
                className="w-full h-full object-contain"
              />
            </div>

            <div className="flex items-center justify-between pt-2 text-xs font-mono text-zinc-400">
              <span>Voice: {playingVideo.voice} · Style: {playingVideo.style}</span>
              <a
                href={`/api/video/projects/${playingVideo.id}/download`}
                download
                className="flex items-center gap-1.5 rounded bg-emerald-500 px-3.5 py-1.5 font-bold text-black hover:bg-emerald-400"
              >
                <Download className="h-3.5 w-3.5" />
                <span>Download MP4</span>
              </a>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
